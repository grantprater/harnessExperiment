"""Build the S2b pipeline-control table from saved P6 run files only (no conclusions).

Usage: python experiments/session_harness/s2b_control_table.py [oci-run-prefix]
  round 1: s2b-oci   (guest --user 65534:65534; exposed the chmod denial)
  round 2: s2b-oci2  (Podman --userns keep-id)   [default]
Writes experiments/session_harness/s2b_runs/S2b-controls-table-<prefix>.md.
"""

import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
RUNS = ROOT / "experiments" / "p6_pilot" / "runs"
PREFIX = sys.argv[1] if len(sys.argv) > 1 else "s2b-oci2"
OUT = ROOT / "experiments" / "session_harness" / "s2b_runs" / f"S2b-controls-table-{PREFIX}.md"
# Expected acceptance, fixed before the runs; trusted-local runs are the reference.
CONTROLS = [
    ("gold", "accepted", f"{PREFIX}-gold", "pipeline-gold"),
    ("noop", "rejected", f"{PREFIX}-noop", "pipeline-noop"),
    ("breaker", "rejected", f"{PREFIX}-breaker", "pipeline-breaker"),
    ("gamer", "rejected", f"{PREFIX}-gamer", "pipeline-gamer"),
    ("tester", "rejected", f"{PREFIX}-tester", "s2b-local-tester"),
]


def read_jsonl(path: Path):
    if not path.exists():
        return []
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def run_status(row: dict) -> str:
    """Status line of the scripted run-tool call, plus the pytest summary line when present."""
    for tool in row.get("tool_results", []):
        if tool["call_id"] != "scripted_run":
            continue
        head = tool["head"].splitlines()
        status = head[1] if len(head) > 1 else "?"
        summary = [line for line in tool["tail"].splitlines()
                   if re_summary(line)]
        return f"{status}; {summary[-1].strip('= ') if summary else 'no summary'}".replace("|", "/")
    return "-"


def re_summary(line: str) -> bool:
    return any(word in line for word in (" passed", " failed", " error", "Interrupted"))


def main() -> None:
    lines = ["# S2b pipeline controls (generated)", ""]
    for client, expected, oci_run, local_run in CONTROLS:
        config_path = RUNS / oci_run / "config.json"
        config = json.loads(config_path.read_text(encoding="utf-8")) if config_path.exists() else {}
        execution = config.get("execution", {})
        oci = {r["task_id"]: r for r in read_jsonl(RUNS / oci_run / "results.jsonl")}
        local = {r["task_id"]: r for r in read_jsonl(RUNS / local_run / "results.jsonl")} if local_run else {}
        tasks = config.get("tasks", sorted(oci))
        matches = sum(1 for t in tasks if t in oci and oci[t]["acceptance"]["status"] == expected)
        lines += [
            f"## {client} (expected: {expected})",
            "",
            f"- OCI run `{oci_run}`: protocol `{config.get('protocol_hash')}`, runner v{config.get('runner_version')}, "
            f"backend `{execution.get('backend')}`, image ID `{execution.get('image_id')}`",
            f"- Source: `{config.get('source_revision')}`",
            f"- Recorded {len(oci)} of {len(tasks)} tasks; matching expectation: {matches}",
            "",
            "| task | OCI acceptance | f2p / p2p | observed tests | collection errors | pytest exit | "
            "revision unchanged | OCI elapsed s | trusted-local acceptance | trusted-local elapsed s | "
            "OCI run-tool status | trusted-local run-tool status |",
            "|---|---|---|---:|---|---:|---|---:|---|---:|---|---|",
        ]
        for task in tasks:
            row = oci.get(task)
            if row is None:
                lines.append(f"| {task} | not recorded | | | | | | | | | | |")
                continue
            acc = row["acceptance"]
            outcomes = acc["criterion_outcomes"]
            unchanged = row.get("initial_workspace_revision") == acc.get("final_workspace_revision")
            reference = local.get(task, {})
            lines.append(
                f"| {task} | {acc['status']} | {outcomes.get('fail-to-pass')} / {outcomes.get('pass-to-pass')} | "
                f"{acc.get('observed_test_count')} | {len(acc.get('collection_errors') or [])} | "
                f"{acc.get('pytest_exit_code')} | {unchanged} | {row.get('elapsed_s')} | "
                f"{(reference.get('acceptance') or {}).get('status', '-')} | {reference.get('elapsed_s', '-')} | "
                f"{run_status(row)} | {run_status(reference)} |"
            )
        lines.append("")
    lines += ["Generated by `s2b_control_table.py` from config.json and results.jsonl only.", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
