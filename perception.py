"""Perceptual Engine for Code / Text Navigation (Foveated & Multi-Scale Perception).

Provides sensory resolutions across the fidelity ladder:
1. Macro Sensor (`extract_outline`):
   - Generates an AST skeleton outline (classes, methods, signatures, types, line ranges)
     without function bodies.
   - Supports modes: 'semantic' (signatures + 1st-line docstrings + types),
     'bare' (signatures only), and 'folded' (structural folding).
   - Auto-inlines small files (<= inline_threshold lines) so models get full context
     in a single saccade without an extra roundtrip.
2. Mesoscopic Sensor (`extract_symbol`):
   - Extracts a specific target class, function, or method by name, with full body
     and surrounding line-numbered context.
3. Foveated Saccade (`inspect_region`):
   - Extracts an exact, bounded slice of lines with line numbers and optional margins.
4. Hygiene utilities:
   - Header boilerplate / copyright stripper.
"""

from __future__ import annotations

import ast
import re
from dataclasses import dataclass
from pathlib import Path
from typing import List, Optional, Tuple, Union


@dataclass
class SymbolInfo:
    name: str
    kind: str  # 'class', 'function', 'async_function', 'method'
    start_line: int
    end_line: int
    signature: str
    docstring_summary: str = ""
    parent: Optional[str] = None


def strip_header_boilerplate(source: str) -> Tuple[str, int]:
    """Strip leading license, copyright, and generated comment blocks.
    
    Returns (cleaned_source, stripped_line_count).
    Preserves module-level docstrings and functional code.
    """
    lines = source.splitlines()
    if not lines:
        return source, 0

    idx = 0
    boilerplate_patterns = [
        re.compile(r"^\s*#.*(?:copyright|license|all rights reserved|spdx|autogenerated|generated by)", re.I),
        re.compile(r"^\s*#.*(?:mit|apache|bsd|gpl|mpl)", re.I),
        re.compile(r"^\s*#\s*[-=*~_]{5,}\s*$"),  # decorative banner line
    ]

    while idx < len(lines):
        line = lines[idx].strip()
        if not line:
            idx += 1
            continue
        if line.startswith("#"):
            if any(p.search(line) for p in boilerplate_patterns):
                idx += 1
                continue
            # Generic comment before any code or docstring
            if idx < 10 and ("http://" in line or "https://" in line or "author" in line.lower()):
                idx += 1
                continue
        break

    if idx > 0 and idx < len(lines):
        return "\n".join(lines[idx:]), idx
    return source, 0


def list_symbols(file_path: Union[str, Path]) -> List[SymbolInfo]:
    """Extract structured catalog of all top-level and class-level symbols."""
    path = Path(file_path)
    if not path.exists():
        return []

    try:
        source = path.read_text(encoding="utf-8")
        tree = ast.parse(source, filename=str(path))
    except Exception:
        return []

    symbols: List[SymbolInfo] = []

    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            start = node.lineno
            end = getattr(node, "end_lineno", start)
            bases = [ast.unparse(b) for b in node.bases]
            base_str = f"({', '.join(bases)})" if bases else ""
            doc = ast.get_docstring(node) or ""
            doc_sum = doc.splitlines()[0].strip() if doc else ""
            symbols.append(SymbolInfo(
                name=node.name,
                kind="class",
                start_line=start,
                end_line=end,
                signature=f"class {node.name}{base_str}",
                docstring_summary=doc_sum
            ))

            for item in node.body:
                if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    m_start = item.lineno
                    m_end = getattr(item, "end_lineno", m_start)
                    prefix = "async def" if isinstance(item, ast.AsyncFunctionDef) else "def"
                    args = ast.unparse(item.args)
                    ret = f" -> {ast.unparse(item.returns)}" if item.returns else ""
                    m_doc = ast.get_docstring(item) or ""
                    m_doc_sum = m_doc.splitlines()[0].strip() if m_doc else ""
                    symbols.append(SymbolInfo(
                        name=f"{node.name}.{item.name}",
                        kind="method",
                        start_line=m_start,
                        end_line=m_end,
                        signature=f"{prefix} {item.name}({args}){ret}",
                        docstring_summary=m_doc_sum,
                        parent=node.name
                    ))

        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            start = node.lineno
            end = getattr(node, "end_lineno", start)
            prefix = "async def" if isinstance(node, ast.AsyncFunctionDef) else "def"
            args = ast.unparse(node.args)
            ret = f" -> {ast.unparse(node.returns)}" if node.returns else ""
            doc = ast.get_docstring(node) or ""
            doc_sum = doc.splitlines()[0].strip() if doc else ""
            symbols.append(SymbolInfo(
                name=node.name,
                kind="async_function" if isinstance(node, ast.AsyncFunctionDef) else "function",
                start_line=start,
                end_line=end,
                signature=f"{prefix} {node.name}({args}){ret}",
                docstring_summary=doc_sum
            ))

    return symbols


def extract_outline(
    file_path: Union[str, Path],
    mode: str = "semantic",
    inline_threshold: int = 50,
    inline_small: bool = True
) -> str:
    """Macro Sensor: Extracts a compressed symbol outline of a Python file.

    Parameters:
    - file_path: Path to the target Python file.
    - mode:
      - 'semantic' (default): Signatures with types, line numbers, and 1-line docstring summaries.
      - 'bare': Signatures and line numbers only (no docstrings, minimal tokens).
      - 'folded': Structural folding (classes/functions outlines + top-level module assignments).
    - inline_threshold: If file total lines <= inline_threshold and inline_small is True,
      returns full numbered source immediately instead of an outline.
    - inline_small: Whether to auto-inline small files.
    """
    path = Path(file_path)
    if not path.exists():
        return f"Error: File '{path}' does not exist."

    try:
        source = path.read_text(encoding="utf-8")
        tree = ast.parse(source, filename=str(path))
    except SyntaxError as e:
        return f"SyntaxError in {path}: {e.msg} at line {e.lineno}"
    except Exception as e:
        return f"Error parsing {path}: {e}"

    lines = source.splitlines()
    total_lines = len(lines)

    # Adaptive short-circuit: Small files are best returned in full
    if inline_small and total_lines <= inline_threshold:
        numbered = [f"[File: {path.name} ({total_lines} lines <= {inline_threshold} threshold. Full source shown)]"]
        for i, line in enumerate(lines, 1):
            numbered.append(f"{i:4d} | {line}")
        return "\n".join(numbered)

    outline = [f"File: {path.name} ({total_lines} lines total)"]

    # Module docstring if present and in semantic mode
    if mode == "semantic":
        mod_doc = ast.get_docstring(tree)
        if mod_doc:
            outline.append(f'  """{mod_doc.splitlines()[0]}..."""')

    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            start = node.lineno
            end = getattr(node, "end_lineno", start)
            bases = [ast.unparse(b) for b in node.bases]
            base_str = f"({', '.join(bases)})" if bases else ""
            decs = [f"@{ast.unparse(d)}" for d in node.decorator_list]
            for dec in decs:
                outline.append(f"  {dec}")
            outline.append(f"  class {node.name}{base_str}:  # L{start}-L{end}")

            if mode in ("semantic", "folded"):
                doc = ast.get_docstring(node)
                if doc:
                    outline.append(f'    """{doc.splitlines()[0]}..."""')

            for item in node.body:
                if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    m_start = item.lineno
                    m_end = getattr(item, "end_lineno", m_start)
                    m_decs = [f"@{ast.unparse(d)}" for d in item.decorator_list]
                    for d in m_decs:
                        outline.append(f"    {d}")
                    args = ast.unparse(item.args)
                    prefix = "async def" if isinstance(item, ast.AsyncFunctionDef) else "def"
                    ret = f" -> {ast.unparse(item.returns)}" if item.returns else ""
                    outline.append(f"    {prefix} {item.name}({args}){ret}  # L{m_start}-L{m_end}")

                    if mode in ("semantic", "folded"):
                        m_doc = ast.get_docstring(item)
                        if m_doc:
                            outline.append(f'      """{m_doc.splitlines()[0]}..."""')

        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            start = node.lineno
            end = getattr(node, "end_lineno", start)
            decs = [f"@{ast.unparse(d)}" for d in node.decorator_list]
            for dec in decs:
                outline.append(f"  {dec}")
            args = ast.unparse(node.args)
            prefix = "async def" if isinstance(node, ast.AsyncFunctionDef) else "def"
            ret = f" -> {ast.unparse(node.returns)}" if node.returns else ""
            outline.append(f"  {prefix} {node.name}({args}){ret}  # L{start}-L{end}")

            if mode in ("semantic", "folded"):
                doc = ast.get_docstring(node)
                if doc:
                    outline.append(f'    """{doc.splitlines()[0]}..."""')

        elif mode == "folded" and isinstance(node, (ast.Assign, ast.AnnAssign)):
            # In folded mode, surface top-level constant definitions
            start = node.lineno
            try:
                raw = lines[start - 1].strip()
                if len(raw) <= 80 and not raw.startswith("_"):
                    outline.append(f"  {raw}  # L{start}")
            except Exception:
                pass

    return "\n".join(outline)


def extract_symbol(
    file_path: Union[str, Path],
    symbol_name: str,
    margin: int = 1
) -> str:
    """Mesoscopic Sensor: Extracts the complete definition of a named class or function.
    
    Supports:
    - Top-level function: 'order_events'
    - Class: 'Calculator'
    - Method: 'Calculator.add' or simply 'add' if unique
    
    Returns the numbered source lines covering the exact symbol definition.
    """
    path = Path(file_path)
    if not path.exists():
        return f"Error: File '{path}' does not exist."

    symbols = list_symbols(path)
    if not symbols:
        return f"Error: No symbols found in '{path.name}'."

    target: Optional[SymbolInfo] = None

    # 1. Exact match (e.g. 'Class.method' or top-level 'func')
    for s in symbols:
        if s.name == symbol_name:
            target = s
            break

    # 2. Case-insensitive or method-only match (e.g. 'method' matching 'Class.method')
    if not target:
        matches = [s for s in symbols if s.name.lower() == symbol_name.lower() or s.name.split(".")[-1].lower() == symbol_name.lower()]
        if len(matches) == 1:
            target = matches[0]
        elif len(matches) > 1:
            names = ", ".join(m.name for m in matches)
            return f"Ambiguous symbol '{symbol_name}'. Matches: {names}. Specify as Class.method."

    if not target:
        avail = ", ".join(s.name for s in symbols[:15])
        return f"Symbol '{symbol_name}' not found in {path.name}. Available: {avail}"

    lines = path.read_text(encoding="utf-8").splitlines()
    total = len(lines)
    start = max(1, target.start_line - margin)
    end = min(total, target.end_line + margin)

    res = [f"--- Symbol View: {target.kind} {target.name} ({path.name} L{target.start_line}-L{target.end_line}) ---"]
    for idx in range(start, end + 1):
        marker = " > " if target.start_line <= idx <= target.end_line else "   "
        res.append(f"{idx:4d}{marker}| {lines[idx - 1]}")
    res.append(f"--- End Symbol ({target.end_line - target.start_line + 1} lines) ---")
    return "\n".join(res)


def extract_elastic(
    file_path: Union[str, Path],
    target_symbol: Optional[str] = None
) -> str:
    """Elastic AST: Module-level overview with selective focus.
    
    - Retains imports, module docstrings, and global constants.
    - The target_symbol (if provided) is expanded in full detail.
    - Sibling functions and classes have their bodies elided to '... [N lines]'.
    """
    path = Path(file_path)
    if not path.exists():
        return f"Error: File '{path}' does not exist."

    try:
        source = path.read_text(encoding="utf-8")
        tree = ast.parse(source, filename=str(path))
    except Exception as e:
        return f"Error parsing {path}: {e}"

    lines = source.splitlines()
    total = len(lines)
    out: List[str] = [f"--- Elastic View: {path.name} ({total} lines, focus: {target_symbol or 'overview'}) ---"]

    for node in tree.body:
        start = node.lineno
        end = getattr(node, "end_lineno", start)

        if isinstance(node, (ast.Import, ast.ImportFrom)):
            for i in range(start, end + 1):
                out.append(f"{i:4d} | {lines[i - 1]}")
        elif isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant) and isinstance(node.value.value, str) and start == 1:
            # Module docstring
            for i in range(start, end + 1):
                out.append(f"{i:4d} | {lines[i - 1]}")
        elif isinstance(node, (ast.Assign, ast.AnnAssign)):
            for i in range(start, end + 1):
                out.append(f"{i:4d} | {lines[i - 1]}")
        elif isinstance(node, ast.ClassDef):
            is_target_class = target_symbol and (target_symbol == node.name or target_symbol.split(".")[0] == node.name)
            decs = [f"@{ast.unparse(d)}" for d in node.decorator_list]
            bases = [ast.unparse(b) for b in node.bases]
            base_str = f"({', '.join(bases)})" if bases else ""
            for dec in decs:
                out.append(f"     |   {dec}")
            out.append(f"{start:4d} | class {node.name}{base_str}:  # L{start}-L{end}")

            doc = ast.get_docstring(node)
            if doc:
                out.append(f'     |     """{doc.splitlines()[0]}..."""')

            for item in node.body:
                if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    m_start = item.lineno
                    m_end = getattr(item, "end_lineno", m_start)
                    m_name = f"{node.name}.{item.name}"
                    is_target_method = target_symbol and (target_symbol in (m_name, item.name) or target_symbol == node.name)

                    if is_target_method:
                        for idx in range(m_start, m_end + 1):
                            out.append(f"{idx:4d} >| {lines[idx - 1]}")
                    else:
                        m_decs = [f"@{ast.unparse(d)}" for d in item.decorator_list]
                        for d in m_decs:
                            out.append(f"     |     {d}")
                        m_args = ast.unparse(item.args)
                        prefix = "async def" if isinstance(item, ast.AsyncFunctionDef) else "def"
                        ret = f" -> {ast.unparse(item.returns)}" if item.returns else ""
                        out.append(f"{m_start:4d} |     {prefix} {item.name}({m_args}){ret}:")
                        m_doc = ast.get_docstring(item)
                        if m_doc:
                            out.append(f'     |       """{m_doc.splitlines()[0]}..."""')
                        hidden_count = max(0, m_end - m_start)
                        out.append(f"     |       ... [{hidden_count} lines folded]  # L{m_start}-L{m_end}")

        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            is_target = target_symbol and (target_symbol == node.name or target_symbol.split(".")[-1] == node.name)
            if is_target:
                for idx in range(start, end + 1):
                    out.append(f"{idx:4d} >| {lines[idx - 1]}")
            else:
                decs = [f"@{ast.unparse(d)}" for d in node.decorator_list]
                for dec in decs:
                    out.append(f"     | {dec}")
                args = ast.unparse(node.args)
                prefix = "async def" if isinstance(node, ast.AsyncFunctionDef) else "def"
                ret = f" -> {ast.unparse(node.returns)}" if node.returns else ""
                out.append(f"{start:4d} | {prefix} {node.name}({args}){ret}:")
                doc = ast.get_docstring(node)
                if doc:
                    out.append(f'     |   """{doc.splitlines()[0]}..."""')
                hidden_count = max(0, end - start)
                out.append(f"     |   ... [{hidden_count} lines folded]  # L{start}-L{end}")

    out.append("--- End Elastic View ---")
    return "\n".join(out)


def find_symbol_topology(
    root_dir: Union[str, Path],
    symbol_name: str,
    max_callers: int = 15
) -> str:
    """Topological Sensor: Analyzes symbol definition, callees, and callers across repository."""
    root = Path(root_dir)
    target_clean = symbol_name.split(".")[-1]
    definition_info: Optional[str] = None
    callees: List[str] = []
    callers: List[Dict[str, Any]] = []

    for py_path in root.rglob("*.py"):
        if "__pycache__" in py_path.parts:
            continue
        try:
            source = py_path.read_text(encoding="utf-8")
            tree = ast.parse(source, filename=str(py_path))
        except Exception:
            continue

        rel_path = py_path.relative_to(root).as_posix()
        lines = source.splitlines()

        # Check for definition
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name == target_clean:
                if not definition_info:
                    ret = f" -> {ast.unparse(node.returns)}" if node.returns else ""
                    sig = f"def {node.name}({ast.unparse(node.args)}){ret}"
                    definition_info = f"{rel_path}:{node.lineno} ({sig})"

                    # Find callees inside this definition
                    for child in ast.walk(node):
                        if isinstance(child, ast.Call):
                            if isinstance(child.func, ast.Name) and child.func.id != target_clean:
                                callees.append(child.func.id)
                            elif isinstance(child.func, ast.Attribute) and child.func.attr != target_clean:
                                callees.append(child.func.attr)

        # Check for callers across all files
        for node in tree.body:
            enclosing = "module"
            if isinstance(node, ast.ClassDef):
                for item in node.body:
                    if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                        for child in ast.walk(item):
                            if isinstance(child, ast.Call):
                                called = getattr(child.func, "id", None) or getattr(child.func, "attr", None)
                                if called == target_clean and not (rel_path in (definition_info or "") and child.lineno == node.lineno):
                                    snippet = lines[child.lineno - 1].strip() if child.lineno <= len(lines) else ""
                                    callers.append({
                                        "file": rel_path,
                                        "line": child.lineno,
                                        "scope": f"{node.name}.{item.name}",
                                        "snippet": snippet
                                    })
            elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                for child in ast.walk(node):
                    if isinstance(child, ast.Call):
                        called = getattr(child.func, "id", None) or getattr(child.func, "attr", None)
                        if called == target_clean and not (rel_path in (definition_info or "") and child.lineno == node.lineno):
                            snippet = lines[child.lineno - 1].strip() if child.lineno <= len(lines) else ""
                            callers.append({
                                "file": rel_path,
                                "line": child.lineno,
                                "scope": node.name,
                                "snippet": snippet
                            })

    out = [f"=== Topology Map for: '{symbol_name}' ==="]
    if definition_info:
        out.append(f"Definition: {definition_info}")
    else:
        out.append(f"Definition: (Symbol definition not located in {root})")

    unique_callees = sorted(set(callees))
    if unique_callees:
        out.append(f"Direct Callees ({len(unique_callees)}): {', '.join(unique_callees[:10])}")
    else:
        out.append("Direct Callees: None detected")

    out.append(f"Callers / Invocations ({len(callers)} found):")
    if not callers:
        out.append("  (No direct calls found across repository)")
    else:
        for c in callers[:max_callers]:
            out.append(f"  - {c['file']}:{c['line']} in {c['scope']}():  {c['snippet']}")
        if len(callers) > max_callers:
            out.append(f"  ... and {len(callers) - max_callers} more call sites")

    return "\n".join(out)


def extract_contract_skeleton(file_path: Union[str, Path]) -> str:
    """Extract strictly parameter checks, assertions, raises, and returns."""
    path = Path(file_path)
    if not path.exists():
        return f"Error: File '{path}' does not exist."

    try:
        source = path.read_text(encoding="utf-8")
        tree = ast.parse(source, filename=str(path))
    except Exception as e:
        return f"Error parsing {path}: {e}"

    lines = source.splitlines()
    out = [f"--- Contract Skeleton: {path.name} ---"]

    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            prefix = "async def" if isinstance(node, ast.AsyncFunctionDef) else "def"
            ret = f" -> {ast.unparse(node.returns)}" if node.returns else ""
            out.append(f"{node.lineno:4d} | {prefix} {node.name}({ast.unparse(node.args)}){ret}:")
            doc = ast.get_docstring(node)
            if doc:
                out.append(f'     |   """{doc.splitlines()[0]}..."""')

            contract_statements = []
            for stmt in node.body:
                if isinstance(stmt, (ast.Assert, ast.Raise, ast.Return)):
                    contract_statements.append((stmt.lineno, getattr(stmt, "end_lineno", stmt.lineno)))
                elif isinstance(stmt, ast.If):
                    # Check if if-body raises or returns
                    has_raise = any(isinstance(sub, (ast.Raise, ast.Return)) for sub in ast.walk(stmt))
                    if has_raise:
                        contract_statements.append((stmt.lineno, getattr(stmt, "end_lineno", stmt.lineno)))

            if not contract_statements:
                out.append(f"     |   ... [{len(node.body)} statements internal logic omitted]")
            else:
                last_end = node.lineno
                for s_start, s_end in contract_statements:
                    if s_start > last_end + 1:
                        out.append(f"     |   ... [{s_start - last_end - 1} lines calculation omitted]")
                    for idx in range(s_start, s_end + 1):
                        out.append(f"{idx:4d} |   {lines[idx - 1].strip()}")
                    last_end = s_end

        elif isinstance(node, ast.ClassDef):
            out.append(f"{node.lineno:4d} | class {node.name}:")
            for item in node.body:
                if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    prefix = "async def" if isinstance(item, ast.AsyncFunctionDef) else "def"
                    ret = f" -> {ast.unparse(item.returns)}" if item.returns else ""
                    out.append(f"{item.lineno:4d} |   {prefix} {item.name}({ast.unparse(item.args)}){ret}:")
                    for stmt in item.body:
                        if isinstance(stmt, (ast.Assert, ast.Raise, ast.Return)):
                            out.append(f"{stmt.lineno:4d} |     {lines[stmt.lineno - 1].strip()}")

    out.append("--- End Contract Skeleton ---")
    return "\n".join(out)


def inspect_region(
    file_path: Union[str, Path],
    start_line: int,
    end_line: int,
    margin: int = 2
) -> str:
    """Foveated Saccade: Extracts a bounded slice of lines with line numbers.

    Includes an optional context margin around the target range.
    """
    path = Path(file_path)
    if not path.exists():
        return f"Error: File '{path}' does not exist."

    lines = path.read_text(encoding="utf-8").splitlines()
    total = len(lines)

    if total == 0:
        return f"--- Empty File: {path.name} ---"

    # Apply margin and bounds clamp
    start = max(1, start_line - margin)
    end = min(total, end_line + margin)

    formatted_lines = [f"--- Saccade View: {path.name} (L{start}-L{end} of {total}) ---"]
    for idx in range(start, end + 1):
        formatted_lines.append(f"{idx:4d} | {lines[idx - 1]}")
    formatted_lines.append("--- End Region ---")

    return "\n".join(formatted_lines)


